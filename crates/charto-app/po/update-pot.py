#!/usr/bin/env python3
"""Rewrites charto.pot, the list of every text of the interface, from the source files.

Run it after adding or changing a text, then add the new texts to each language's .po file
(`msgmerge -U de.po charto.pot` does that, if gettext is installed).

The texts are the strings in tr("...") calls of qml/main.qml and src/filedialog.rs, the
names of the undo steps, apply("...") in charto-core's document.rs, and the categories, names and
descriptions of the symbols in assets/symbols/*/description.
"""
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

here = Path(__file__).resolve().parent
app = here.parent
core = app.parent / "charto-core"
symbols = app.parent.parent / "assets" / "symbols"

CALL = re.compile(r'(?<![A-Za-z_.])tr\("((?:[^"\\]|\\.)*)"\)')
STEP = re.compile(r'apply\("((?:[^"\\]|\\.)*)"')


def strings(path, pattern):
    return [json.loads('"' + m + '"') for m in pattern.findall(path.read_text(encoding="utf-8"))]


def symbol_texts():
    """Categories (without the position after the colon), names and descriptions of the symbols."""
    cats, names, descs = [], [], []
    for path in sorted(symbols.glob("*/description")):
        symbol = ET.parse(path).getroot().find("knittingSymbol")
        if symbol is None:
            continue
        for tag, bucket in (("category", cats), ("symbolName", names), ("symbolDescription", descs)):
            element = symbol.find(tag)
            if element is not None and element.text and element.text.strip():
                text = element.text.strip()
                bucket.append(text.split(":")[0] if tag == "category" else text)
    return cats + names + descs


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


ids = []
for text in (strings(app / "qml" / "main.qml", CALL)
             + strings(app / "src" / "filedialog.rs", CALL)
             + strings(core / "src" / "document.rs", STEP)
             + symbol_texts()):
    if text not in ids:
        ids.append(text)

out = [
    '# Texts of the Charto interface. Generated by update-pot.py; do not edit by hand.',
    'msgid ""',
    'msgstr ""',
    '"Project-Id-Version: Charto\\n"',
    '"MIME-Version: 1.0\\n"',
    '"Content-Type: text/plain; charset=UTF-8\\n"',
    '"Content-Transfer-Encoding: 8bit\\n"',
    "",
]
for text in ids:
    out += [f"msgid {quote(text)}", 'msgstr ""', ""]
(here / "charto.pot").write_text("\n".join(out), encoding="utf-8")
print(f"wrote charto.pot with {len(ids)} texts")
